/** 세 칸 중 어디인지(0·1·2). */
export function bin3(value, [lo, hi]) {
  if (value < lo) return 0;
  if (value > hi) return 2;
  return 1;
}

/** 두 칸 중 어디인지(0·1). */
export function bin2(value, cut) {
  return value > cut ? 1 : 0;
}
