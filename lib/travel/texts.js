// 이름 추천 결과에 붙는 "재미용 해석" 문구 모음.
// 이름의 실제 뜻(meaning_kr, 사실 정보)과 섞이지 않도록 따로 관리합니다.
// {nick} 뒤에는 조사 대신 항상 "님"을, {city} 뒤에는 받침과 무관한 "에서/의"만 붙입니다.

// 이름 옆 현지 표기 줄. "Ngọc · Ngoc"처럼 로마자가 성조 표시만 뺀 같은 글자면 한 번만 보여줍니다.
export function nameLocalLine(n) {
  const plain = n.name_local
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D");
  return plain === n.romanized ? n.name_local : `${n.name_local} · ${n.romanized}`;
}

